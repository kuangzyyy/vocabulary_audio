"""Tests for Wikimedia Commons candidate parsing and license filtering."""

from __future__ import annotations

from typing import Any

from backend.app.services.audio_provider import (
    AudioCandidate,
    available_accents,
    candidate_from_page,
    is_acceptable_license,
)


def make_page(
    title: str,
    *,
    license_name: str = "CC BY-SA 3.0",
    description: str = "Pronunciation of a word",
    categories: str = "U.S. English pronunciation",
    derivatives: list[dict[str, Any]] | None = None,
    original_url: str = "https://upload.wikimedia.org/wikipedia/commons/5/52/Example.ogg",
) -> dict[str, Any]:
    if derivatives is None:
        derivatives = [
            {
                "src": "https://upload.wikimedia.org/wikipedia/commons/transcoded/5/52/Example.ogg/Example.ogg.mp3",
                "type": "audio/mpeg",
            },
            {
                "src": original_url,
                "type": 'audio/ogg; codecs="vorbis"',
            },
        ]
    return {
        "title": title,
        "videoinfo": [
            {
                "url": original_url,
                "descriptionurl": (
                    "https://commons.wikimedia.org/wiki/"
                    + title.replace(" ", "_")
                ),
                "mime": "application/ogg",
                "extmetadata": {
                    "LicenseShortName": {"value": license_name},
                    "LicenseUrl": {
                        "value": "https://creativecommons.org/licenses/by-sa/3.0/"
                    },
                    "Artist": {
                        "value": '<a href="//commons.wikimedia.org/wiki/User:Tester">Tester</a>'
                    },
                    "ImageDescription": {"value": description},
                    "Categories": {"value": categories},
                },
                "derivatives": derivatives,
            }
        ],
    }


def test_us_candidate_uses_mp3_transcode_and_cleans_attribution() -> None:
    candidate = candidate_from_page(make_page("File:En-us-hello.ogg"))

    assert candidate is not None
    assert candidate.title == "File:En-us-hello.ogg"
    assert candidate.accent == "us"
    assert candidate.mime == "audio/mpeg"
    assert candidate.audio_url.endswith(".mp3")
    assert candidate.license_name == "CC BY-SA 3.0"
    assert candidate.license_url is not None
    assert candidate.attribution == "Tester"
    assert candidate.source_page.startswith("https://commons.wikimedia.org/wiki/")


def test_uk_and_gb_titles_both_map_to_uk() -> None:
    assert candidate_from_page(make_page("File:En-uk-click.ogg")).accent == "uk"
    assert candidate_from_page(make_page("File:En-gb-click.ogg")).accent == "uk"


def test_lingua_libre_recording_is_unknown_accent() -> None:
    candidate = candidate_from_page(
        make_page("File:LL-Q1860 (eng)-Tester-hello.wav")
    )
    assert candidate is not None
    assert candidate.accent == "unknown"


def test_untrusted_title_prefix_is_rejected() -> None:
    assert candidate_from_page(make_page("File:Other-hello.ogg")) is None


def test_noncommercial_license_is_rejected() -> None:
    page = make_page("File:En-us-hello.ogg", license_name="CC BY-NC 4.0")
    assert candidate_from_page(page) is None


def test_no_derivative_license_is_rejected() -> None:
    page = make_page("File:En-us-hello.ogg", license_name="CC BY-ND 4.0")
    assert candidate_from_page(page) is None


def test_synthetic_recording_is_rejected() -> None:
    page = make_page(
        "File:En-us-hello.ogg",
        description="Synthetic speech generated by a TTS system",
    )
    assert candidate_from_page(page) is None


def test_public_domain_is_accepted() -> None:
    candidate = candidate_from_page(
        make_page("File:En-us-hello.ogg", license_name="Public domain")
    )
    assert candidate is not None


def test_license_filter_examples() -> None:
    assert is_acceptable_license("CC0")
    assert is_acceptable_license("Public domain")
    assert is_acceptable_license("CC BY 3.0 us")
    assert is_acceptable_license("CC BY-SA 4.0")
    assert not is_acceptable_license("CC BY-NC 4.0")
    assert not is_acceptable_license("CC BY-ND 4.0")
    assert not is_acceptable_license("All rights reserved")
    assert not is_acceptable_license("")


def test_original_file_is_used_when_no_transcode_exists() -> None:
    page = make_page(
        "File:En-us-example.ogg",
        derivatives=[],
        original_url="https://upload.wikimedia.org/wikipedia/commons/7/77/Example.ogg",
    )
    candidate = candidate_from_page(page)
    assert candidate is not None
    assert candidate.mime == "audio/ogg"
    assert candidate.audio_url.endswith(".ogg")


def test_available_accents_are_ordered_and_deduplicated() -> None:
    candidates = [
        AudioCandidate(
            "us1", "us", "https://upload.wikimedia.org/a.mp3",
            "s", "audio/mpeg", "CC0", None, None,
        ),
        AudioCandidate(
            "uk1", "uk", "https://upload.wikimedia.org/b.mp3",
            "s", "audio/mpeg", "CC0", None, None,
        ),
        AudioCandidate(
            "us2", "us", "https://upload.wikimedia.org/c.mp3",
            "s", "audio/mpeg", "CC0", None, None,
        ),
    ]
    assert available_accents(candidates) == ["us", "uk"]
